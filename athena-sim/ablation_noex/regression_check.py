"""Regression check for the graph_noex patch (run from ablation_noex/:  python -B regression_check.py).

1. Prompts of the four original conditions, regenerated by this patched harness, must equal the prompts logged in
   the frozen GSCS test runs (o3-mini and GPT-6 Luna) character for character.
2. graph_noex must equal graph with the example lines ("  OK : ..." / "  BAD: ...") removed, and differ from it only there.
No LLM is called.
"""
import collections, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.dirname(HERE))
from athena.packs import load_pack, select_split
from athena.retrieval import Retriever
from athena.runner import make_prompt

RUNS = {"rename": ["../runs/test_luna_gscs_rename", "../runs/test_o3mini_gscs_rename"],
        "comment": ["../runs/test_luna_gscs_comment", "../runs/test_o3mini_gscs_comment"]}
pack = load_pack("gscs"); ret = Retriever(pack, chunk_k=3, top_k=None, n_examples=2)
ok = True; lines = []
for task, dirs in RUNS.items():
    units = {u.unit_id: u for u in select_split(pack.rename_units() if task == "rename" else pack.comment_units(), "test")}
    for d in dirs:
        c = collections.Counter()
        for line in open(os.path.join(HERE, d, "trials.jsonl"), encoding="utf-8"):
            t = json.loads(line)
            p, _ = make_prompt(pack, ret, task, units[t["unit_id"]], t["condition"])
            c[(t["condition"], p == t["prompt"])] += 1
        bad = {k: v for k, v in c.items() if not k[1]}
        ok &= not bad
        lines.append(f"{task} {d}: " + ", ".join(f"{k[0]} {'same' if k[1] else 'DIFF'} {v}" for k, v in sorted(c.items())))
    n = same = 0
    for u in units.values():
        g, _ = make_prompt(pack, ret, task, u, "graph"); x, ctx = make_prompt(pack, ret, task, u, "graph_noex")
        stripped = "\n".join(l for l in g.split("\n") if not (l.startswith("  OK : ") or l.startswith("  BAD: ")))
        n += 1; same += (stripped == x and g != x)
    ok &= same == n
    lines.append(f"{task}: graph_noex == graph minus example lines (and differs from graph) for {same}/{n} test units")
print("\n".join(lines)); print("REGRESSION", "PASS" if ok else "FAIL")
open(os.path.join(HERE, "regression_check.txt"), "w", encoding="utf-8").write("\n".join(lines) + "\nREGRESSION " + ("PASS" if ok else "FAIL") + "\n")
